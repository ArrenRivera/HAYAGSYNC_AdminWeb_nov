begin;

alter table public.students
  add column if not exists is_active boolean not null default true;

alter table public.etl_runs
  add column if not exists students_updated integer not null default 0
    check (students_updated >= 0),
  add column if not exists students_deactivated integer not null default 0
    check (students_deactivated >= 0);

do $migration$
begin
  if exists (
    select 1
    from public.school_sections
    group by grade, section_name, academic_year
    having count(*) > 1
  ) then
    raise exception
      'Duplicate school_sections exist for a grade, section, and academic year. Resolve them before enabling current roster sync.';
  end if;
end
$migration$;

create unique index if not exists school_sections_roster_key_uidx
  on public.school_sections (grade, section_name, academic_year);

create table if not exists public.etl_pending_staff (
  id bigint generated by default as identity primary key,
  batch_id uuid not null
    references public.etl_runs (batch_id) on delete cascade,
  full_name text not null,
  email text not null,
  requested_role text not null,
  assigned_section text not null default '',
  review_status text not null default 'pending'
    check (review_status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create unique index if not exists etl_pending_staff_pending_email_uidx
  on public.etl_pending_staff (lower(email))
  where review_status = 'pending';

alter table public.etl_pending_staff enable row level security;
revoke all on table public.etl_pending_staff from public, anon, authenticated;
grant select on table public.etl_pending_staff to authenticated;

drop policy if exists etl_pending_staff_select_roster_admin
  on public.etl_pending_staff;
create policy etl_pending_staff_select_roster_admin
  on public.etl_pending_staff for select to authenticated
  using (private.has_roster_admin_role());

revoke insert, update, delete on table public.students
  from public, anon, authenticated;
revoke insert, update, delete on table public.etl_runs, public.etl_rejected_records
  from public, anon, authenticated;

create or replace function public.append_roster_import(
  p_source_file text,
  p_students jsonb,
  p_staff jsonb,
  p_rejected jsonb,
  p_actor_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $function$
declare
  v_batch_id uuid;
  v_student_count integer;
  v_staff_count integer;
  v_rows_received integer;
  v_students_inserted integer := 0;
  v_students_updated integer := 0;
  v_students_deactivated integer := 0;
  v_staff_staged integer := 0;
  v_rejections jsonb := coalesce(p_rejected, '[]'::jsonb);
  v_row jsonb;
  v_lrn text;
  v_name text;
  v_grade text;
  v_section text;
  v_academic_year text;
  v_workbook_academic_year text;
  v_email text;
  v_role text;
  v_assigned_section text;
  v_reason text;
  v_seen_lrns text[] := array[]::text[];
  v_seen_emails text[] := array[]::text[];
  v_rejected_count integer;
begin
  if p_actor_user_id is null or not exists (
    select 1
    from public.users as u
    where u.id = p_actor_user_id
      and u.is_active
      and u.role = 'principal'
  ) then
    raise exception 'Only an active Principal account can import current roster data.';
  end if;

  if coalesce(p_source_file, '') = '' or length(p_source_file) > 255 then
    raise exception 'A valid source workbook name is required.';
  end if;
  if jsonb_typeof(p_students) is distinct from 'array'
    or jsonb_typeof(p_staff) is distinct from 'array'
    or jsonb_typeof(v_rejections) is distinct from 'array' then
    raise exception 'Students, Staff, and rejected rows must be arrays.';
  end if;

  select count(*) into v_student_count
  from jsonb_array_elements(p_students);
  select count(*) into v_staff_count
  from jsonb_array_elements(p_staff);
  v_rows_received := v_student_count + v_staff_count
    + jsonb_array_length(v_rejections);

  if v_student_count = 0 then
    raise exception 'The Students sheet must contain at least one current student.';
  end if;
  if v_rows_received > 5000 then
    raise exception 'The workbook must contain no more than 5000 rows.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('hayagsync-current-roster-import', 0));

  insert into public.etl_runs (
    source_file, status, details
  )
  values (
    p_source_file,
    'started',
    jsonb_build_object(
      'uploaded_by', p_actor_user_id::text,
      'rows_received', v_rows_received,
      'students_received', v_student_count,
      'staff_received', v_staff_count
    )
  )
  returning batch_id into v_batch_id;

  for v_row in select value from jsonb_array_elements(p_students)
  loop
    v_lrn := regexp_replace(coalesce(v_row ->> 'lrn', ''), '\s+', '', 'g');
    v_name := btrim(coalesce(v_row ->> 'name', ''));
    v_grade := btrim(coalesce(v_row ->> 'grade', ''));
    v_section := btrim(coalesce(v_row ->> 'section', ''));
    v_academic_year := btrim(coalesce(v_row ->> 'academic_year', ''));
    v_reason := '';

    if v_lrn !~ '^[0-9]{11,12}$' then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'LRN must contain 11 or 12 digits.');
    end if;
    if v_name = '' or length(v_name) > 200 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Student name is required and must be 200 characters or fewer.');
    end if;
    if v_grade = '' or length(v_grade) > 40 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Grade is required and must be 40 characters or fewer.');
    end if;
    if v_section = '' or length(v_section) > 100 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Section is required and must be 100 characters or fewer.');
    end if;
    if v_academic_year = '' or length(v_academic_year) > 30 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Academic year is required and must be 30 characters or fewer.');
    elsif v_workbook_academic_year is null then
      v_workbook_academic_year := v_academic_year;
    elsif v_workbook_academic_year <> v_academic_year then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'All student rows must belong to one current academic year.');
    end if;
    if v_lrn <> '' and lower(v_lrn) = any(v_seen_lrns) then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Duplicate LRN in this workbook.');
    elsif v_lrn <> '' then
      v_seen_lrns := array_append(v_seen_lrns, lower(v_lrn));
    end if;

    if v_reason <> '' then
      v_rejections := v_rejections || jsonb_build_array(jsonb_build_object(
        'sheet', 'Students',
        'row_number', v_row -> 'row_number',
        'identifier', coalesce(nullif(v_lrn, ''), 'Blank LRN'),
        'reason', v_reason
      ));
    end if;
  end loop;

  for v_row in select value from jsonb_array_elements(p_staff)
  loop
    v_email := lower(btrim(coalesce(v_row ->> 'email', '')));
    v_name := btrim(coalesce(v_row ->> 'name', ''));
    v_role := coalesce(v_row ->> 'role', '');
    v_assigned_section := btrim(coalesce(v_row ->> 'assigned_section', ''));
    v_reason := '';

    if v_name = '' or length(v_name) > 200 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Staff name is required and must be 200 characters or fewer.');
    end if;
    if v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
      or length(v_email) > 320 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'A valid staff email of 320 characters or fewer is required.');
    end if;
    if v_role not in (
      'adviser', 'board_of_discipline', 'ministrong_tagasubaybay',
      'osd', 'principal', 'school_president'
    ) then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Staff role is not supported.');
    end if;
    if length(v_assigned_section) > 150 then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Assigned section must be 150 characters or fewer.');
    end if;
    if v_email <> '' and v_email = any(v_seen_emails) then
      v_reason := concat_ws(' ', nullif(v_reason, ''), 'Duplicate email in this workbook.');
    elsif v_email <> '' then
      v_seen_emails := array_append(v_seen_emails, v_email);
    end if;

    if v_reason <> '' then
      v_rejections := v_rejections || jsonb_build_array(jsonb_build_object(
        'sheet', 'Staff',
        'row_number', v_row -> 'row_number',
        'identifier', coalesce(nullif(v_email, ''), 'Blank email'),
        'reason', v_reason
      ));
    end if;
  end loop;

  if jsonb_array_length(v_rejections) > 0 then
    insert into public.etl_rejected_records (
      batch_id, sheet, row_number, identifier, reason, row_data
    )
    select
      v_batch_id,
      rejected.value ->> 'sheet',
      case
        when rejected.value ->> 'row_number' ~ '^[1-9][0-9]*$'
          then (rejected.value ->> 'row_number')::integer
        else null
      end,
      nullif(rejected.value ->> 'identifier', ''),
      rejected.value ->> 'reason',
      '{}'::jsonb
    from jsonb_array_elements(v_rejections) as rejected(value);

    v_rejected_count := jsonb_array_length(v_rejections);
    update public.etl_runs
    set status = 'failed',
        ended_at = now(),
        rejected_count = v_rejected_count,
        details = details || jsonb_build_object(
          'message', 'The complete workbook was rejected; no roster rows were changed.'
        )
    where batch_id = v_batch_id;

    return jsonb_build_object(
      'success', false,
      'message', 'The complete workbook was rejected. No roster rows were changed.',
      'rejected_count', v_rejected_count,
      'students_inserted', 0,
      'students_updated', 0,
      'students_deactivated', 0,
      'staff_inserted', 0
    );
  end if;

  insert into public.school_sections (grade, section_name, academic_year)
  select distinct
    student.value ->> 'grade',
    student.value ->> 'section',
    student.value ->> 'academic_year'
  from jsonb_array_elements(p_students) as student(value)
  on conflict (grade, section_name, academic_year) do nothing;

  select count(*) into v_students_inserted
  from jsonb_array_elements(p_students) as incoming(value)
  where not exists (
    select 1 from public.students as existing
    where existing.lrn = incoming.value ->> 'lrn'
  );

  select count(*) into v_students_updated
  from jsonb_array_elements(p_students) as incoming(value)
  join public.students as existing
    on existing.lrn = incoming.value ->> 'lrn'
  where existing.name is distinct from incoming.value ->> 'name'
     or existing.grade is distinct from incoming.value ->> 'grade'
     or existing.section is distinct from incoming.value ->> 'section'
     or existing.academic_year is distinct from incoming.value ->> 'academic_year'
     or not existing.is_active;

  select count(*) into v_students_deactivated
  from public.students as existing
  where existing.is_active
    and not exists (
      select 1
      from jsonb_array_elements(p_students) as incoming(value)
      where incoming.value ->> 'lrn' = existing.lrn
    );

  insert into public.students as target (
    lrn, name, grade, section, academic_year, is_active
  )
  select
    value ->> 'lrn',
    value ->> 'name',
    value ->> 'grade',
    value ->> 'section',
    value ->> 'academic_year',
    true
  from jsonb_array_elements(p_students)
  on conflict (lrn) do update
  set name = excluded.name,
      grade = excluded.grade,
      section = excluded.section,
      academic_year = excluded.academic_year,
      is_active = true,
      updated_at = now()
  where target.name is distinct from excluded.name
     or target.grade is distinct from excluded.grade
     or target.section is distinct from excluded.section
     or target.academic_year is distinct from excluded.academic_year
     or not target.is_active;

  update public.students as existing
  set is_active = false,
      updated_at = now()
  where existing.is_active
    and not exists (
      select 1
      from jsonb_array_elements(p_students) as incoming(value)
      where incoming.value ->> 'lrn' = existing.lrn
    );

  insert into public.etl_pending_staff (
    batch_id, full_name, email, requested_role, assigned_section
  )
  select
    v_batch_id,
    incoming.value ->> 'name',
    lower(incoming.value ->> 'email'),
    incoming.value ->> 'role',
    coalesce(incoming.value ->> 'assigned_section', '')
  from jsonb_array_elements(p_staff) as incoming(value)
  where not exists (
    select 1 from public.users as existing
    where lower(existing.email) = lower(incoming.value ->> 'email')
  )
    and not exists (
      select 1 from public.etl_pending_staff as pending
      where lower(pending.email) = lower(incoming.value ->> 'email')
        and pending.review_status = 'pending'
    )
  on conflict do nothing;
  get diagnostics v_staff_staged = row_count;

  update public.etl_runs
  set status = 'completed',
      ended_at = now(),
      students_inserted = v_students_inserted,
      students_updated = v_students_updated,
      students_deactivated = v_students_deactivated,
      staff_inserted = v_staff_staged,
      rejected_count = 0,
      details = details || jsonb_build_object(
        'message', 'Current roster synchronized; inactive student records were retained.'
      )
  where batch_id = v_batch_id;

  return jsonb_build_object(
    'success', true,
    'message', 'Current roster synchronized successfully.',
    'students_inserted', v_students_inserted,
    'students_updated', v_students_updated,
    'students_deactivated', v_students_deactivated,
    'staff_inserted', v_staff_staged,
    'rejected_count', 0
  );
end
$function$;

revoke all on function public.append_roster_import(text, jsonb, jsonb, jsonb, uuid)
  from public, anon, authenticated;
grant execute on function public.append_roster_import(text, jsonb, jsonb, jsonb, uuid)
  to service_role;

commit;
