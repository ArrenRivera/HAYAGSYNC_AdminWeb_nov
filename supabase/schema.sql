-- HayagSYNC baseline schema for a new Supabase project.
-- RLS is enabled and no client policies are created by this script.
-- Do not add a service_role key to the browser app.

create table if not exists public.users (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null unique,
  name text not null,
  role text not null check (role in (
    'adviser',
    'board_of_discipline',
    'ministrong_tagasubaybay',
    'osd',
    'principal',
    'school_president'
  )),
  assigned_section text,
  title text,
  department text,
  avatar text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.parent_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  phone_number text,
  created_at timestamptz not null default now(),
  constraint parent_profiles_user_id_fkey
    foreign key (user_id) references public.users (id) on delete cascade
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  lrn varchar(12) not null unique
    check (lrn ~ '^[0-9]{11,12}$'),
  name text not null,
  grade text not null,
  section text not null,
  academic_year text not null,
  parent_id uuid references public.parent_profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.parent_student_guardianships (
  id bigint generated by default as identity primary key,
  parent_profile_id uuid not null
    references public.parent_profiles (id) on delete cascade,
  student_id bigint not null
    references public.students (id) on delete cascade,
  relationship_type text not null default 'Guardian',
  is_primary_contact boolean not null default false,
  created_at timestamptz not null default now(),
  unique (parent_profile_id, student_id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  student_id bigint references public.students (id) on delete set null,
  student_name text not null,
  student_grade text not null default '',
  student_section text not null default '',
  title text not null,
  category text not null,
  description text not null default '',
  incident_date timestamptz not null default now(),
  incident_location text not null default 'Campus',
  urgency_level text not null default 'Moderate',
  bully_name text,
  bully_grade_section text,
  witnesses text,
  evidence_url text,
  evidence_verification_state text not null default 'Unverified',
  ai_summary text,
  status text not null default 'Pending',
  report_source text not null default 'Registered Parent',
  parent_name text,
  discipline_action text,
  discipline_notes text,
  appealed_reason text,
  appeal_count integer not null default 0 check (appeal_count >= 0),
  escalation_reason text,
  escalation_notes text,
  escalated_to text,
  board_referred boolean not null default false,
  hearing_notes text,
  board_decision text,
  board_recommendations text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.timeline_events (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.reports (id) on delete cascade,
  title text not null,
  description text not null default '',
  actor_name text not null default 'System',
  actor_role text not null default 'System',
  created_at timestamptz not null default now()
);

create table if not exists public.etl_runs (
  id bigint generated by default as identity primary key,
  batch_id uuid not null unique default gen_random_uuid(),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  status text not null default 'started'
    check (status in ('started', 'completed', 'completed_with_errors', 'failed')),
  source_file text,
  students_inserted integer not null default 0 check (students_inserted >= 0),
  staff_inserted integer not null default 0 check (staff_inserted >= 0),
  rejected_count integer not null default 0 check (rejected_count >= 0),
  details jsonb not null default '{}'::jsonb
);

create table if not exists public.etl_rejected_records (
  id bigint generated by default as identity primary key,
  batch_id uuid not null
    references public.etl_runs (batch_id) on delete cascade,
  sheet text not null,
  row_number integer check (row_number > 0),
  identifier text,
  reason text not null,
  row_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users (id) on delete set null,
  user_email text,
  user_role text,
  action text not null,
  entity_name text,
  record_id text,
  old_values jsonb,
  new_values jsonb,
  ip_address inet,
  created_at timestamptz not null default now()
);

create table if not exists public.login_history (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users (id) on delete set null,
  user_email text,
  success boolean not null default false,
  ip_address inet,
  user_agent text,
  created_at timestamptz not null default now()
);

create table if not exists public.security_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users (id) on delete set null,
  user_email text,
  event_type text not null,
  severity text not null default 'low'
    check (severity in ('low', 'medium', 'high', 'critical')),
  description text not null default '',
  ip_address inet,
  created_at timestamptz not null default now()
);

create index if not exists reports_status_idx on public.reports (status);
create index if not exists reports_category_idx on public.reports (category);
create index if not exists reports_incident_date_idx on public.reports (incident_date);
create index if not exists reports_created_at_idx on public.reports (created_at desc);
create index if not exists timeline_events_report_id_idx on public.timeline_events (report_id);
create index if not exists students_name_idx on public.students (name);
create index if not exists students_grade_section_idx on public.students (grade, section);
create index if not exists etl_rejected_records_batch_id_idx on public.etl_rejected_records (batch_id);
create index if not exists activity_logs_created_at_idx on public.activity_logs (created_at desc);
create index if not exists login_history_created_at_idx on public.login_history (created_at desc);
create index if not exists security_events_created_at_idx on public.security_events (created_at desc);

alter table public.users enable row level security;
alter table public.parent_profiles enable row level security;
alter table public.students enable row level security;
alter table public.parent_student_guardianships enable row level security;
alter table public.reports enable row level security;
alter table public.timeline_events enable row level security;
alter table public.etl_runs enable row level security;
alter table public.etl_rejected_records enable row level security;
alter table public.activity_logs enable row level security;
alter table public.login_history enable row level security;
alter table public.security_events enable row level security;

grant select, insert, update, delete on
  public.users,
  public.parent_profiles,
  public.students,
  public.parent_student_guardianships,
  public.reports,
  public.timeline_events,
  public.etl_runs,
  public.etl_rejected_records,
  public.activity_logs,
  public.login_history,
  public.security_events
to authenticated;

grant usage, select on all sequences in schema public to authenticated;
