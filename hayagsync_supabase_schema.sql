create or replace function private.matches_guardian_report(
  p_student_id bigint,
  p_student_name text,
  p_student_grade text,
  p_student_section text,
  p_student_academic_year text,
  p_reporter_name text
)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth
as $function$
  select exists (
    select 1
    from public.students as s
    join public.parent_student_guardianships as g on g.student_id = s.id
    join public.parent_profiles as p on p.id = g.parent_profile_id
    join public.users as u on u.id = p.user_id
    where s.id = p_student_id
      and p.user_id = auth.uid()
      and s.name = p_student_name
      and s.grade = p_student_grade
      and s.section = p_student_section
      and (p_student_academic_year is null
        or s.academic_year = p_student_academic_year)
      and u.name = p_reporter_name
  )
$function$;

create or replace function private.can_access_student(
  p_student_id bigint,
  p_grade text,
  p_section text,
  p_academic_year text
)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth
as $function$
  select private.has_global_case_access()
    or (
      private.has_any_role(array[
        'adviser', 'ministrong_tagasubaybay', 'principal'
      ])
      and exists (
        select 1
        from public.staff_section_assignments as a
        join public.school_sections as s on s.id = a.section_id
        where a.user_id = auth.uid()
          and s.grade = p_grade
          and s.section_name = p_section
          and s.academic_year = p_academic_year
      )
    )
    or (
      private.current_role() = 'board_of_discipline'
      and exists (
        select 1
        from public.reports as r
        where r.student_id = p_student_id
          and (
            r.board_referred
            or lower(r.status) in (
              'escalated to board of discipline',
              'referred to board of discipline',
              'under review (board hearing)',
              'forwarded to school president'
            )
            or lower(r.status) like 'resolved (%'
          )
      )
    )
    or (
      private.current_role() = 'school_president'
      and exists (
        select 1
        from public.reports as r
        where r.student_id = p_student_id
          and r.board_referred
          and lower(r.status) in (
            'forwarded to school president', 'resolved', 'expelled'
          )
      )
    )
$function$;

create or replace function private.can_access_report(p_report_id bigint)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth
as $function$
  select coalesce((
    select case
      when private.has_global_case_access() then true
      when private.current_role() = 'board_of_discipline' then
        r.board_referred
        or lower(r.status) in (
          'escalated to board of discipline',
          'referred to board of discipline',
          'under review (board hearing)',
          'forwarded to school president'
        )
        or lower(r.status) like 'resolved (%'
      when private.current_role() = 'school_president' then
        r.board_referred
        and lower(r.status) in (
          'forwarded to school president', 'resolved', 'expelled'
        )
      else
        r.student_id is not null
        and s.id is not null
        and private.can_access_student(
          s.id, s.grade, s.section, s.academic_year
        )
    end
    from public.reports as r
    left join public.students as s on s.id = r.student_id
    where r.id = p_report_id
  ), false)
$function$;

