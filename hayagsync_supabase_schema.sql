create or replace function private.enforce_report_workflow()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $function$
declare
  actor_role text;
  old_status text;
  new_status text;
  stage_allowed boolean := false;
begin
  if auth.uid() is null then
    return new;
  end if;

  select u.role
    into actor_role
  from public.users as u
  where u.id = auth.uid()
    and u.is_active;

  if actor_role is null then
    raise exception 'An active HayagSYNC profile is required to update a case.';
  end if;

  new.updated_by_user_id := auth.uid();

  -- Workflow methods currently issue a direct update followed by a generic
  -- update. Permit that second, unchanged write without a second stage action.
  if (to_jsonb(new) - 'updated_at' - 'updated_by_user_id')
      is not distinct from
     (to_jsonb(old) - 'updated_at' - 'updated_by_user_id') then
    return new;
  end if;

  if new.student_id is distinct from old.student_id
    or new.reporter_user_id is distinct from old.reporter_user_id
    or new.student_name is distinct from old.student_name
    or new.student_grade is distinct from old.student_grade
    or new.student_section is distinct from old.student_section
    or new.student_academic_year is distinct from old.student_academic_year
    or new.title is distinct from old.title
    or new.category is distinct from old.category
    or new.description is distinct from old.description
    or new.incident_date is distinct from old.incident_date
    or new.incident_location is distinct from old.incident_location
    or new.urgency_level is distinct from old.urgency_level
    or new.bully_name is distinct from old.bully_name
    or new.bully_grade_section is distinct from old.bully_grade_section
    or new.witnesses is distinct from old.witnesses
    or new.evidence_url is distinct from old.evidence_url
    or new.evidence_verification_state is distinct from old.evidence_verification_state
    or new.ai_summary is distinct from old.ai_summary
    or new.report_source is distinct from old.report_source
    or new.parent_name is distinct from old.parent_name
    or new.appealed_reason is distinct from old.appealed_reason
    or new.appeal_count is distinct from old.appeal_count
    or new.created_at is distinct from old.created_at then
    raise exception 'Report intake details are immutable through direct client updates.';
  end if;

  old_status := lower(pg_catalog.btrim(old.status));
  new_status := lower(pg_catalog.btrim(new.status));

  if old_status in ('pending', 'recent report', 'ongoing report',
                    'escalated to osd', 'appealed') then
    stage_allowed := actor_role = 'osd'
      and new_status = any (array[
        'recent report', 'ongoing report',
        'forwarded for initial intervention',
        'escalated to ministrong tagasubaybay',
        'escalated to osd', 'escalated to principal'
      ]);
  elsif old_status in ('forwarded for initial intervention',
                       'scheduled_meeting',
                       'escalated to ministrong tagasubaybay') then
    stage_allowed := actor_role = any (array[
      'adviser', 'ministrong_tagasubaybay'
    ])
      and new_status = any (array[
        'resolved', 'escalated to osd and principal',
        'ongoing report', 'scheduled_meeting'
      ]);
  elsif old_status in ('escalated to osd and principal',
                       'escalated to principal') then
    stage_allowed := actor_role = any (array['osd', 'principal'])
      and new_status = any (array[
        'resolved', 'escalated to board of discipline',
        'referred to board of discipline', 'appealed',
        'community service', 'expelled', 'ongoing report'
      ]);
  elsif old_status in ('escalated to board of discipline',
                       'referred to board of discipline',
                       'under review (board hearing)')
        or old_status like 'resolved (%' then
    stage_allowed := actor_role = 'board_of_discipline'
      and (
        new_status = any (array[
          'forwarded to school president',
          'under review (board hearing)', 'resolved', 'ongoing report'
        ])
        or new_status like 'resolved (%'
      );
  elsif old_status = 'forwarded to school president' then
    stage_allowed := actor_role = 'school_president'
      and new_status = 'resolved';
  elsif old_status in ('resolved', 'community service', 'expelled') then
    stage_allowed := actor_role = 'osd'
      and new_status = any (array[
        'resolved', 'appealed', 'community service', 'expelled'
      ]);
  end if;

  if not stage_allowed then
    raise exception 'Role % cannot move case from status % to %.',
      actor_role, old.status, new.status;
  end if;

  if actor_role <> 'board_of_discipline'
    and (
      new.hearing_notes is distinct from old.hearing_notes
      or new.board_decision is distinct from old.board_decision
      or new.board_recommendations is distinct from old.board_recommendations
    ) then
    raise exception 'Only the Board of Discipline may change board findings or decision fields.';
  end if;

  if actor_role in ('adviser', 'ministrong_tagasubaybay')
    and new.board_referred is distinct from old.board_referred then
    raise exception 'Only OSD or an assigned principal may refer a case to the Board.';
  end if;

  if new.board_referred is distinct from old.board_referred
    and (
      actor_role not in ('osd', 'principal')
      or old_status not in (
        'escalated to osd and principal',
        'escalated to principal'
      )
    ) then
    raise exception 'A case may be referred to the Board only from the OSD/principal stage.';
  end if;

  if old_status in ('pending', 'recent report', 'ongoing report',
                    'escalated to osd', 'appealed')
    and new.discipline_action is distinct from old.discipline_action then
    raise exception 'Disciplinary action cannot be set during initial OSD assessment.';
  end if;

  if actor_role = 'board_of_discipline'
    and (
      new.escalation_reason is distinct from old.escalation_reason
      or new.escalation_notes is distinct from old.escalation_notes
      or new.escalated_to is distinct from old.escalated_to
    ) then
    raise exception 'The Board may not rewrite the prior escalation record.';
  end if;

  if actor_role = 'school_president'
    and (
      new.discipline_action is distinct from old.discipline_action
      or new.board_referred is distinct from old.board_referred
      or new.escalation_reason is distinct from old.escalation_reason
      or new.escalation_notes is distinct from old.escalation_notes
      or new.escalated_to is distinct from old.escalated_to
      or new.hearing_notes is distinct from old.hearing_notes
      or new.board_decision is distinct from old.board_decision
      or new.board_recommendations is distinct from old.board_recommendations
    ) then
    raise exception 'The School President may affirm the decision but may not rewrite prior case findings.';
  end if;

  return new;
end
$function$;

create or replace function private.prepare_report_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $function$
declare
  actor record;
  roster_student public.students%rowtype;
begin
  if auth.uid() is null then
    return new;
  end if;

  select u.id, u.name, u.role
    into actor
  from public.users as u
  where u.id = auth.uid()
    and u.is_active;

