create table public.parent_student_guardianships (
  id bigint generated by default as identity primary key,
  parent_profile_id uuid not null
    references public.parent_profiles (id) on delete cascade,
  student_id bigint not null
    references public.students (id) on delete cascade,
  relationship_type text not null default 'Guardian',
  is_primary_contact boolean not null default false,
  created_at timestamptz not null default now(),
  unique (parent_profile_id, student_id)
);

create unique index one_primary_guardian_per_student_uidx
  on public.parent_student_guardianships (student_id)
  where is_primary_contact;

create table public.staff_section_assignments (
  id uuid primary key default gen_random_uuid(),
