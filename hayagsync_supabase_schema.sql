    raise exception 'Only an authenticated parent/guardian may submit this report.';
  end if;

  select s.*
    into roster_student
  from public.students as s
  where s.id = p_student_id
    and private.is_guardian_of_student(s.id);

  if roster_student.id is null then
    raise exception 'The selected student is not linked to this guardian account.';
  end if;

  insert into public.reports (
    student_id,
    reporter_user_id,
    student_name,
    student_grade,
    student_section,
    student_academic_year,
    title,
    category,
    description,
    incident_date,
    incident_location,
    urgency_level,
    bully_name,
    bully_grade_section,
    witnesses,
    report_source,
    parent_name,
    status
  )
  values (
    roster_student.id,
    auth.uid(),
    roster_student.name,
    roster_student.grade,
    roster_student.section,
    roster_student.academic_year,
    p_title,
    p_category,
    coalesce(p_description, ''),
    coalesce(p_incident_date, pg_catalog.now()),
    coalesce(p_incident_location, 'Campus'),
    coalesce(p_urgency_level, 'Moderate'),
    p_bully_name,
    p_bully_grade_section,
    p_witnesses,
    'Registered Parent',
    null,
    'Pending'
  )
  returning id into new_report_id;

  return query
    select r.id, r.title, r.status, r.created_at
    from public.reports as r
    where r.id = new_report_id;
end
