-- HayagSYNC schema for a new, empty Supabase project.
-- This script does not migrate existing data and must not be run over an
-- existing HayagSYNC schema. The preflight below aborts rather than altering
-- existing application tables.
-- Run once in Supabase SQL Editor, then configure the private schema as
-- unexposed in Supabase API settings.

begin;

-- 1. Extensions and prerequisites
-- gen_random_uuid() is built into supported Supabase PostgreSQL versions.

do $preflight$
declare
  existing_tables text;
begin
  select string_agg(c.relname, ', ' order by c.relname)
    into existing_tables
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('r', 'p', 'v', 'm', 'f')
    and c.relname = any (array[
      'users', 'parent_profiles', 'students', 'parent_student_guardianships',
      'school_sections', 'staff_section_assignments', 'school_settings',
      'incident_categories', 'reports', 'timeline_events', 'case_appeals',
      'appeal_supporting_documents', 'community_service_assignments',
      'community_service_hour_logs', 'expulsion_records', 'notifications',
      'etl_runs', 'etl_rejected_records', 'activity_logs', 'login_history',
      'security_events', 'parent_report_status'
    ]);

  if existing_tables is not null then
    raise exception
      'HayagSYNC objects already exist in public: %. Stop here and inspect/migrate the existing schema; this installer is for a new project only.',
      existing_tables;
  end if;
end
$preflight$;

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

-- 2. Custom types and enums
-- Statuses/categories remain text because the current UI uses free-form values.
-- User roles are checked in the profile table to preserve readable API values.

-- 3. Reference tables
create table public.school_sections (
  id uuid primary key default gen_random_uuid(),
  grade text not null,
  section_name text not null,
  academic_year text not null,
  created_at timestamptz not null default now(),
  unique (grade, section_name, academic_year)
);

create table public.incident_categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text not null default '',
  severity_default text not null default 'Moderate',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.school_settings (
  singleton_id smallint primary key default 1 check (singleton_id = 1),
  school_name text not null,
  division text not null default '',
  academic_year text not null,
  policy_framework text not null default '',
  auto_escalate_days integer not null default 0 check (auto_escalate_days >= 0),
  require_guardian_countersign boolean not null default false,
  updated_at timestamptz not null default now()
);

-- 4. Core user and profile tables
-- Passwords belong only in Supabase Auth (auth.users), never in public.users.
create table public.users (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  name text not null,
  role text not null default 'parent'
    check (role in (
      'parent',
      'adviser',
      'board_of_discipline',
      'ministrong_tagasubaybay',
      'osd',
      'principal',
      'school_president'
    )),
  title text,
  department text,
  avatar text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index users_email_lower_uidx on public.users (lower(email));

create table public.parent_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  phone_number text,
  created_at timestamptz not null default now(),
  constraint parent_profiles_user_id_fkey
    foreign key (user_id) references public.users (id) on delete cascade,
  unique (user_id)
);

-- 5. Academic and enrollment tables
create table public.students (
  id bigint generated by default as identity primary key,
  lrn varchar(12) not null unique check (lrn ~ '^[0-9]{11,12}$'),
  name text not null,
  grade text not null,
  section text not null,
  academic_year text not null,
  -- Compatibility pointer to the primary guardian; the join table below is
  -- authoritative when a student has multiple guardians.
  parent_id uuid references public.parent_profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
