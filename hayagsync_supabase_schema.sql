  new.created_at := pg_catalog.now();
  new.updated_at := new.created_at;
  new.updated_by_user_id := actor.id;

  if actor.role = 'parent' then
    select s.*
      into roster_student
    from public.students as s
    where s.id = new.student_id
      and private.is_guardian_of_student(s.id);

    if roster_student.id is null then
      raise exception 'A guardian may report only a student linked to their account.';
    end if;

    new.student_name := roster_student.name;
    new.student_grade := roster_student.grade;
    new.student_section := roster_student.section;
    new.student_academic_year := roster_student.academic_year;
    new.report_source := 'Registered Parent';
    new.status := 'Pending';
    new.urgency_level := coalesce(new.urgency_level, 'Moderate');
    new.evidence_url := null;
    new.evidence_verification_state := 'Unverified';
    new.ai_summary := null;
    new.discipline_action := null;
    new.discipline_notes := null;
    new.appealed_reason := null;
    new.appeal_count := 0;
    new.escalation_reason := null;
    new.escalation_notes := null;
    new.escalated_to := null;
    new.board_referred := false;
    new.hearing_notes := null;
    new.board_decision := null;
    new.board_recommendations := null;
  elsif new.report_source = 'Registered Parent' then
    new.report_source := 'Staff';
  end if;

  return new;
end
