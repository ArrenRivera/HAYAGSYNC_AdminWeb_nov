  p_student_id bigint,
  p_title text,
  p_category text,
  p_description text,
  p_incident_date timestamptz default pg_catalog.now(),
  p_incident_location text default 'Campus',
  p_urgency_level text default 'Moderate',
  p_bully_name text default null,
